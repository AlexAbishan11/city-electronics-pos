    private void displayProducts() {
        panelProducts.removeAll();

        
        List<Product> allProducts = utils.ProductData.productList;

        
        java.util.List<Product> filteredProducts = new java.util.ArrayList<>();
        for (Product p : allProducts) {
            if (p.getCategory().equalsIgnoreCase(categoryName)) {
                filteredProducts.add(p);
            }
        }

        panelProducts.setLayout(new GridLayout(0, 3, 10, 10)); // 3 columns, spacing 10px

        for (Product product : filteredProducts) {
            JPanel itemPanel = new JPanel();
            itemPanel.setLayout(new BoxLayout(itemPanel, BoxLayout.Y_AXIS));
            itemPanel.setBorder(BorderFactory.createEmptyBorder(10, 10, 10, 10));

            
            ImageIcon icon = null;
            try {
                icon = new ImageIcon(getClass().getResource("/" + product.getImagePath()));
            } catch (Exception e) {
                System.out.println("Image not found for: " + product.getName());
                icon = new ImageIcon(); // empty icon fallback
            }
            Image img = icon.getImage().getScaledInstance(120, 120, Image.SCALE_SMOOTH);
            JLabel imgLabel = new JLabel(new ImageIcon(img));
            imgLabel.setAlignmentX(Component.CENTER_ALIGNMENT);

            JLabel nameLabel = new JLabel(product.getName(), JLabel.CENTER);
            nameLabel.setAlignmentX(Component.CENTER_ALIGNMENT);

            JLabel priceLabel = new JLabel("Rs. " + product.getPrice(), JLabel.CENTER);
            priceLabel.setAlignmentX(Component.CENTER_ALIGNMENT);

            
            JPanel qtyPanel = new JPanel();
            qtyPanel.add(new JLabel("Qty:"));
            JTextField qtyField = new JTextField("1", 3);
            qtyPanel.add(qtyField);

            
            JButton addToCartBtn = new JButton("Add to Cart");
            addToCartBtn.addActionListener(e -> {
                try {
                    int qty = Integer.parseInt(qtyField.getText().trim());
                    if (qty <= 0) {
                        JOptionPane.showMessageDialog(this, "Invalid quantity!");
                        return;
                    }

                    models.CartItem item = new models.CartItem(product.getName(), product.getPrice(), qty);
                    models.Cart.addItem(loggedInPhone, item);
                    JOptionPane.showMessageDialog(this, "Item added to cart!");
                } catch (NumberFormatException ex) {
                    JOptionPane.showMessageDialog(this, "Please enter a valid number.");
                }
            });

            itemPanel.add(imgLabel);
            itemPanel.add(nameLabel);
            itemPanel.add(priceLabel);
            itemPanel.add(qtyPanel);
            itemPanel.add(addToCartBtn);

            panelProducts.add(itemPanel);
        }

        panelProducts.revalidate();
        panelProducts.repaint();
    }

    

