     private void generateBill() {
       StringBuilder sb = new StringBuilder();
    sb.append("City Electronics\n");
    sb.append("Shop contact number:020123456789 /0771234567\n");
    sb.append("-------------------------\n");
    sb.append("Customer Phone number: ").append(customerPhone).append("\n\n");
    sb.append("Items:\n");

    double grandTotal = 0;

    for (Product p : cart) {
        double itemTotal = p.price * p.quantity;
        grandTotal += itemTotal;
        
        sb.append(" - ").append(p.name)
          .append(" | Rs. ").append(p.price)
          .append(" x ").append(p.quantity)
          .append(" = Rs. ").append(itemTotal).append("\n");
    }

    sb.append("\nGrand Total: Rs. ").append(grandTotal).append("\n");
    sb.append("Status: Pending\n");
    sb.append("*****Thank you for shopping****** \n");
    sb.append("Please click Place Order button >> \n");

    txtBill.setText(sb.toString());
}

