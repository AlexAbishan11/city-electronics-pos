    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
        String phone = txtPhone.getText();
    String password = new String(txtPassword.getPassword());

    boolean found = false;

    for (models.Customer c : utils.CustomerData.customerList) {
        if (c.phone.equals(phone) && c.password.equals(password)) {
            found = true;
            break;
        }
    }

    if (found) {
        JOptionPane.showMessageDialog(this, "Login successful!");
            String loggedInPhone = phone;
       new CustomerDashboardUI(loggedInPhone).setVisible(true);
        this.dispose();
    } else {
        JOptionPane.showMessageDialog(this, "Invalid phone or password or sign up first");
    }
    }//GEN-LAST:event_btnLoginActionPerformed

    private void btnSignupActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignupActionPerformed
        // TODO add your handling code here:
         String phone = txtPhone.getText();
    String password = new String(txtPassword.getPassword());

    if (phone.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter phone and password!");
        return;
    }
    if (phone.length() < 9) {
    JOptionPane.showMessageDialog(this, "please check your Phone number");
    return;
    }
    if (password.length() < 4) {
    JOptionPane.showMessageDialog(this, "Password must be at least 4 characters long!");
    return;
    }

    for (models.Customer c : utils.CustomerData.customerList) {
        if (c.phone.equals(phone)) {
            JOptionPane.showMessageDialog(this, "Phone already registered!");
            return;
        }
    }

    utils.CustomerData.customerList.add(new models.Customer(phone, password));
    JOptionPane.showMessageDialog(this, "Signup successful! You can log in now.");
    clearFields();
    }//GEN-LAST:event_btnSignupActionPerformed

