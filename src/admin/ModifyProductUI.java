    private void cmbProductsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbProductsActionPerformed
        // TODO add your handling code here:
        int index = cmbProducts.getSelectedIndex();
    if (index >= 0 && index < utils.ProductData.productList.size()) {
        models.Product p = utils.ProductData.productList.get(index);
        txtName.setText(p.name);
        comboCategory.setSelectedItem(p.category);
        txtPrice.setText(String.valueOf(p.price));
        txtImagePath.setText(p.imagePath);
    }
    }//GEN-LAST:event_cmbProductsActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int index = cmbProducts.getSelectedIndex();
    if (index == -1) {
        JOptionPane.showMessageDialog(this, "Please select a product.");
        return;
    }

    try {
        String name = txtName.getText();
        String category = (String) comboCategory.getSelectedItem();
        double price = Double.parseDouble(txtPrice.getText());
        String imagePath = txtImagePath.getText();

        models.Product p = utils.ProductData.productList.get(index);
        p.name = name;
        p.category = category;
        p.price = price;
        p.imagePath = imagePath;

        JOptionPane.showMessageDialog(this, "Product updated successfully!");
        cmbProducts.removeAllItems();
        for (models.Product prod : utils.ProductData.productList) {
            cmbProducts.addItem(prod.name);
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid price.");
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

