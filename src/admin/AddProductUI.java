    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
       String name = txtName.getText();
   String category = (String) comboCategory.getSelectedItem();
    String priceStr = txtPrice.getText();
    String imagePath = txtImagePath.getText();

    if(name.isEmpty() || category.isEmpty() || priceStr.isEmpty() || imagePath.isEmpty()) {
        JOptionPane.showMessageDialog(this, "All fields are required.");
        return;
    }
    
    if (!imagePath.startsWith("images/") || imagePath.length() <= "images/".length()) {
    JOptionPane.showMessageDialog(this, "please input image path properly.");
    return;
}

    try {
        double price = Double.parseDouble(priceStr);
        Product product = new Product(name, category, price, imagePath, 1);
        utils.ProductData.productList.add(product);

        JOptionPane.showMessageDialog(this, "Product added successfully!");

        
        txtName.setText("");
        comboCategory.setSelectedIndex(0);
        txtPrice.setText("");
        txtImagePath.setText("images/");

    } catch(NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid price. Enter a number.");
    }
    }//GEN-LAST:event_btnAddActionPerformed

